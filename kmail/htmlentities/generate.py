#!/usr/bin/env python3
# generate.py [entities.json] > ../htmlentities.h
#
# KMail's table of HTML 5 named character references (kmail/htmlentities.h,
# used by cidrewriter.cpp) from WHATWG's entities.json, kept next to this
# script.  To update: download https://html.spec.whatwg.org/entities.json
# over the copy here, run this script, commit both and the table.
# entities.json is part of the HTML Living Standard, (c) WHATWG (Apple,
# Google, Mozilla, Microsoft), licensed under CC BY 4.0; downloaded on
# 2026-11-24 (sha256 d741d877ac77c4194c4ad526b5b4a19aef8dfe411ab840a466891cdbb9f362e6).
#
# The table: every name of the standard (without '&' and ';'), sorted by
# bytes for a binary search; its one or two code points; whether it is a
# legacy name (one a browser also takes without the semicolon).  Every
# legacy name has a twin with the semicolon and the same value in
# entities.json: the generator checks that, and the other assumptions.
import json, re, sys

src = sys.argv[1] if len(sys.argv) > 1 else __file__.rsplit('/', 1)[0] + '/entities.json'
d = json.load(open(src, encoding='utf-8'))
entries = {}
for key, value in d.items():
    m = re.fullmatch(r'&([A-Za-z0-9]+)(;?)', key)
    assert m, key
    cps = value['codepoints']
    assert 1 <= len(cps) <= 2 and cps[0] < 1 << 21 and (len(cps) == 1 or cps[1] <= 0xffff), key
    if m.group(2):
        entries.setdefault(m.group(1), [cps, False])
    else:
        assert d.get(key + ';', {}).get('codepoints') == cps, key
for key in d:
    if not key.endswith(';'):
        entries[key[1:]][1] = True
names = sorted(entries, key=lambda s: s.encode('ascii'))
assert max(len(n) for n in names) < 32

blob, offsets = [], []
size = 0
for n in names:
    offsets.append(size)
    blob.append(n)
    size += len(n) + 1
assert size < 1 << 16

out = sys.stdout
out.write('// HTML 5 named character references: generated by htmlentities/generate.py\n'
          '// from htmlentities/entities.json (WHATWG, https://html.spec.whatwg.org/entities.json).\n'
          '// Do not edit: regenerate.  %d names, %d of them legacy ones.\n\n' % (len(names), sum(entries[n][1] for n in names)))
out.write('#ifndef __KMAIL_HTMLENTITIES_H__\n#define __KMAIL_HTMLENTITIES_H__\n\n')
out.write('namespace {\n\n')
out.write('  // the names, NUL-terminated, sorted (bytes)\n  const char htmlEntityNames[] =\n')
line = '    "'
for n in names:
    piece = n + '\\0'
    if len(line) + len(piece) > 100:
        out.write(line + '"\n')
        line = '    "'
    line += piece
out.write(line + '";\n\n')
out.write('  // name: offset in htmlEntityNames; first: the first code point, bit 31\n'
          '  // set for a legacy name; second: the second code point (BMP) or 0\n'
          '  struct HtmlEntity { unsigned short name, second; unsigned int first; };\n')
out.write('  const unsigned int htmlEntityCount = %d;\n' % len(names))
out.write('  const HtmlEntity htmlEntities[] = {\n')
row = []
for n, off in zip(names, offsets):
    cps, legacy = entries[n]
    first = cps[0] | (0x80000000 if legacy else 0)
    second = cps[1] if len(cps) > 1 else 0
    row.append('{%d,0x%x,0x%xu}' % (off, second, first))
    if len(row) == 6:
        out.write('    ' + ','.join(row) + ',\n')
        row = []
if row:
    out.write('    ' + ','.join(row) + '\n')
out.write('  };\n\n} // anon namespace\n\n#endif // __KMAIL_HTMLENTITIES_H__\n')
